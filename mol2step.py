def sphere_radius_mm(vdw_angstroms, scale, vdw_scale):
    """VdW radius → model sphere radius in mm."""
    return vdw_angstroms * vdw_scale * scale / 2.0


def tube_radius_mm(scale, bond_scale, override=None):
    """Compute bond tube radius from H VdW and scale factors."""
    if override is not None:
        return override
    return VDW_RADII["H"] * bond_scale * scale / 2.0


def validate_geometry(mol, scale, vdw_scale, bond_scale,
                      tube_radius_override=None):
    """
    Validate spatial contact between all spheres and tubes.
    Pure numpy — does NOT require CadQuery.
    """
    t_r = tube_radius_mm(scale, bond_scale, tube_radius_override)
    MIN_EXCESS = max(0.05, t_r * 0.01)

    print("\n  ── Spatial contact validation ──")
    issues = 0

    for bond in mol.bonds:
        a1, a2 = mol.atoms[bond.atom1_idx], mol.atoms[bond.atom2_idx]
        p1, p2 = a1.pos * scale, a2.pos * scale
        d = p2 - p1
        length = np.linalg.norm(d)
        if length < 0.01:
            print(f"  !! Zero-length bond {a1.element}{bond.atom1_idx}-"
                  f"{a2.element}{bond.atom2_idx}")
            issues += 1
            continue
        d_hat = d / length

        r1 = max(sphere_radius_mm(a1.vdw_radius, scale, vdw_scale),
                 t_r + MIN_EXCESS)
        r2 = max(sphere_radius_mm(a2.vdw_radius, scale, vdw_scale),
                 t_r + MIN_EXCESS)

        # Cylinder goes center-to-center (no extension)
        cyl_start = p1
        cyl_end = p2
        cyl_length = length

        if bond.order == 1:
            offsets = [(np.zeros(3), t_r, "single")]
        else:
            mr = t_r * 0.65
            od = t_r * 0.85
            if abs(d_hat[0]) < 0.9:
                perp = np.cross(d_hat, [1, 0, 0])
            else:
                perp = np.cross(d_hat, [0, 1, 0])
            perp = perp / np.linalg.norm(perp)
            offsets = []
            for k in range(bond.order):
                theta = math.pi * k if bond.order == 2 else \
                    2 * math.pi * k / bond.order
                off = perp * od * math.cos(theta)
                if bond.order > 1:
                    perp2 = np.cross(d_hat, perp)
                    off = off + perp2 * od * math.sin(theta)
                offsets.append((off, mr, f"multi-k{k}"))

        for off, cr, kind in offsets:
            for label, center, sph_r in [
                (f"{a1.element}{bond.atom1_idx}", p1, r1),
                (f"{a2.element}{bond.atom2_idx}", p2, r2),
            ]:
                axis_origin = cyl_start + off
                v = center - axis_origin
                proj = np.dot(v, d_hat)
                closest = axis_origin + proj * d_hat
                axis_dist = np.linalg.norm(center - closest)

                # For center-to-center: atom center is at proj=0 or proj=length
                # The cylinder endpoint coincides with atom center
                # Overlap = sphere extends past cylinder end along axis
                # Overlap depth along axis = sph_r (for centered bonds)
                #                          = sqrt(sph_r^2 - axis_dist^2) for offset
                if axis_dist < sph_r:
                    depth = math.sqrt(sph_r**2 - axis_dist**2)
                    in_range = (-0.01 <= proj <= cyl_length + 0.01)
                    # Also check sphere excess over tube
                    excess = sph_r - cr
                    status = "OK" if (in_range and excess > 0) else \
                             "TANGENT" if (in_range and excess <= 0) else \
                             "AXIS_SHORT"
                elif axis_dist < sph_r + cr:
                    depth = 0
                    in_range = (-0.01 <= proj <= cyl_length + 0.01)
                    status = "PARTIAL" if in_range else "MISS"
                else:
                    depth = 0
                    status = "NO_CONTACT"
                    in_range = False

                ok = status == "OK"
                if not ok:
                    issues += 1
                sym = "  " if ok else ">>"
                off_mag = np.linalg.norm(off)
                off_s = f"off={off_mag:.2f}" if off_mag > 0.01 else "ctr"
                print(f"  {sym} {a1.element}{bond.atom1_idx}-"
                      f"{a2.element}{bond.atom2_idx} -> {label}: "
                      f"ax_d={axis_dist:.3f} sph_r={sph_r:.2f} "
                      f"cyl_r={cr:.2f} proj={proj:.1f}/{cyl_length:.1f} "
                      f"depth={depth:.2f} excess={sph_r-cr:.2f} "
                      f"{off_s} {kind} [{status}]")

    if issues:
        print(f"\n  !! {issues} issues found !!")
    else:
        print(f"\n  All {len(mol.bonds)} bonds validated — "
              f"sphere_r > tube_r at every junction.")
    return issues


def build_model(mol, scale=10.0, vdw_scale=1.0, bond_scale=1.0,
                tube_radius_override=None, fillet_size=None,
                no_fillet=False, add_base=False, base_thickness=3.0,
                base_margin=5.0):
    """
    Per-atom hub architecture with OCCT rolling-ball fillets.

    Each atom produces exactly one hub solid:

        hub_A = sphere_A  union  tube(A->B1)  union  tube(A->B2)  union ...

    CadQuery .fillet() is then applied to the complete hub.  OCCT's
    BRepFilletAPI_MakeFillet finds every sphere-cylinder intersection
    edge on the hub and computes a rolling-ball fillet conforming to
    both surfaces simultaneously.  No torus approximations.

    Because each atom's sphere appears in exactly one hub, there are no
    duplicate-sphere artefacts.  Bond tubes appear in two hubs (one per
    endpoint) and overlap at the bond midpoint; this is harmless in a
    compound of overlapping solids.

    Junction geometry (overlap, angle) is computed analytically from the
    model parameters before any OCCT work, so problems are reported
    immediately rather than discovered in a post-hoc STEP probe.

    Returns a CadQuery Compound of hub solids.
    """
    import cadquery as cq

    t_r = tube_radius_mm(scale, bond_scale, tube_radius_override)
    if fillet_size is None:
        fillet_size = t_r * 0.3
    MIN_EXCESS = max(0.05, t_r * 0.01)

    def atom_r(atom):
        return max(sphere_radius_mm(atom.vdw_radius, scale, vdw_scale),
                   t_r + MIN_EXCESS)

    # ── Sizing and junction-geometry table ─────────────────────────────
    print(f"  Scale: {scale} mm/A  VdW: {vdw_scale}x  Bond: {bond_scale}x")
    print(f"  Tube radius: {t_r:.3f} mm   fillet: {fillet_size:.3f} mm")
    print()
    print(f"  {'Elem':4s}  {'sph_r':>7s}  {'overlap':>8s}  {'angle':>7s}  status")
    print(f"  {'----':4s}  {'-----':>7s}  {'-------':>8s}  {'-----':>7s}  ------")
    for elem in sorted(set(a.element for a in mol.atoms)):
        vdw = VDW_RADII.get(elem, DEFAULT_VDW_RADIUS)
        r   = max(sphere_radius_mm(vdw, scale, vdw_scale), t_r + MIN_EXCESS)
        ov  = r - t_r
        z   = math.sqrt(max(0.0, r*r - t_r*t_r))
        ang = math.degrees(math.asin(min(1.0, z / r)))
        st  = "ok" if ov >= 1.0 else ("marginal" if ov >= 0.3 else "GAP RISK")
        print(f"  {elem:4s}  {r:7.3f}  {ov:8.3f}  {ang:7.1f}  {st}")
    print()

    # ── Analytical gap check across all bonds ──────────────────────────
    gap_count = 0
    for bond in mol.bonds:
        for atom in (mol.atoms[bond.atom1_idx], mol.atoms[bond.atom2_idx]):
            if (atom_r(atom) - t_r) < 0.3:
                gap_count += 1
    if gap_count:
        print(f"  WARNING: {gap_count} junctions have overlap < 0.3 mm"
              f" -- reduce --bond-scale or raise --vdw-scale")
    else:
        print("  All junction overlaps >= 0.3 mm  (ok)")
    print()

    # ── Compute per-bond tube geometry (once per bond) ─────────────────
    # For double/triple bonds: parallel tubes offset from the bond axis.
    # Offsets are computed once from the canonical bond direction so both
    # endpoints receive identical offset vectors (no sign-flip confusion).
    #
    # atom_tubes[atom.index] = list of (start_mm, end_mm, cyl_radius)

    atom_tubes = {a.index: [] for a in mol.atoms}

    for bond in mol.bonds:
        a1  = mol.atoms[bond.atom1_idx]
        a2  = mol.atoms[bond.atom2_idx]
        p1  = np.asarray(a1.pos * scale, dtype=float)
        p2  = np.asarray(a2.pos * scale, dtype=float)
        vec = p2 - p1
        L   = float(np.linalg.norm(vec))
        if L < 0.01:
            continue
        d = vec / L

        if bond.order == 1:
            atom_tubes[a1.index].append((p1, p2, t_r))
            atom_tubes[a2.index].append((p2, p1, t_r))
        else:
            mr  = t_r * 0.65          # reduced radius per parallel tube
            od  = t_r * 0.85          # offset from bond axis
            ref = np.array([1.0, 0.0, 0.0]) if abs(d[0]) < 0.9 \
                  else np.array([0.0, 1.0, 0.0])
            u   = np.cross(d, ref);  u /= np.linalg.norm(u)   # first perp
            v   = np.cross(d, u)                                # second perp
            for k in range(bond.order):
                theta = (math.pi * k) if bond.order == 2 else \
                        (2.0 * math.pi * k / bond.order)
                off = od * (math.cos(theta) * u + math.sin(theta) * v)
                atom_tubes[a1.index].append((p1 + off, p2 + off, mr))
                atom_tubes[a2.index].append((p2 + off, p1 + off, mr))

    # ── Build hubs ─────────────────────────────────────────────────────
    print(f"  Building {len(mol.atoms)} hubs (sphere + tubes, then fillet)...")

    hub_solids  = []
    fillet_ok   = 0
    fillet_fail = 0

    for atom in mol.atoms:
        pos = np.asarray(atom.pos * scale, dtype=float)
        r   = atom_r(atom)

        # Start with the atom sphere
        hub = _make_sphere(cq, pos, r)

        # Fuse every bond tube into this hub
        for (start, end, cyl_r) in atom_tubes[atom.index]:
            cyl = _make_cylinder(cq, start, end, cyl_r)
            if cyl is None:
                continue
            try:
                hub = hub.union(cyl)
            except Exception as exc:
                print(f"    {atom.element}{atom.index}: tube union failed"
                      f" ({exc}) -- adding tube separately")
                hub_solids.append(cyl)

        # Apply OCCT rolling-ball fillet to the complete hub.
        # .fillet() finds all convex circular edges (sphere-cylinder
        # intersections) and blends them with a surface tangent to both
        # the sphere and the cylinder.
        if not no_fillet and fillet_size > 0 and atom_tubes[atom.index]:
            filleted = False
            for sz in [fillet_size, fillet_size * 0.5, fillet_size * 0.25]:
                try:
                    candidate = hub.fillet(sz)
                    if len(candidate.val().Faces()) > 0:
                        hub      = candidate
                        filleted = True
                        fillet_ok += 1
                        break
                except Exception:
                    pass
            if not filleted:
                fillet_fail += 1

        hub_solids.append(hub)

    if not no_fillet:
        print(f"  Fillets: {fillet_ok} ok, {fillet_fail} failed")
    print(f"  Compound: {len(hub_solids)} hub bodies")

    # ── Optional base plate ────────────────────────────────────────────
    if add_base:
        max_r = max(atom_r(a) for a in mol.atoms)
        bb_min, bb_max = mol.bounding_box()
        bmin = np.asarray(bb_min * scale, dtype=float)
        bmax = np.asarray(bb_max * scale, dtype=float)
        z_bot = float(bmin[2]) - max_r - 0.5
        w  = float(bmax[0] - bmin[0]) + 2 * base_margin + 2 * max_r
        dd = float(bmax[1] - bmin[1]) + 2 * base_margin + 2 * max_r
        cx = float(bmin[0] + bmax[0]) / 2.0
        cy = float(bmin[1] + bmax[1]) / 2.0
        base = (cq.Workplane("XY")
                .box(w, dd, base_thickness)
                .translate(cq.Vector(cx, cy, z_bot - base_thickness / 2.0)))
        try:
            base = base.edges("|Z").fillet(base_thickness * 0.4)
        except Exception:
            pass
        hub_solids.append(base)

    shapes = [s.val() if hasattr(s, 'val') else s for s in hub_solids]
    return cq.Compound.makeCompound(shapes)


def check_step_gaps(step_file, mol, scale=10.0, vdw_scale=1.0, bond_scale=1.0,
                    tube_radius_override=None, n_samples=12, probe_depth=0.5):
    """
    Analytical junction geometry check against a STEP file.

    Computes sphere-tube overlap and junction angle for every bond endpoint
    directly from the model parameters -- no point-in-solid probing needed.

    overlap  = sphere_radius - tube_radius
               (how deeply the tube is embedded in the sphere)
    angle    = arcsin(sqrt(sphere_r^2 - tube_r^2) / sphere_r)
               (the angle between the bond axis and the sphere surface
                at the junction circle; 90deg = ideal, 0deg = tangent)

    Both metrics are purely geometric and computed instantly.  The STEP
    file is loaded only to verify that the expected number of hub bodies
    is present.

    Flags:
      GAP      -- overlap < 0.3 mm  OR  angle < 10 deg
      MARGINAL -- overlap < 1.0 mm  OR  angle < 20 deg
    """
    import cadquery as cq

    print("=" * 70)
    print(f"JUNCTION GEOMETRY CHECK  ({step_file})")
    print("=" * 70)

    # Load STEP just to count bodies
    try:
        compound = cq.importers.importStep(str(step_file))
        n_bodies  = len(compound.solids().vals())
        expected  = len(mol.atoms)
        body_note = "ok" if n_bodies >= expected \
                    else f"WARNING expected >= {expected}"
        print(f"  STEP solid bodies: {n_bodies}  [{body_note}]")
    except Exception as exc:
        print(f"  Could not load STEP file: {exc}")

    t_r       = tube_radius_mm(scale, bond_scale, tube_radius_override)
    MIN_EXCESS = max(0.05, t_r * 0.01)

    def atom_r(atom):
        return max(sphere_radius_mm(atom.vdw_radius, scale, vdw_scale),
                   t_r + MIN_EXCESS)

    print(f"  Tube radius: {t_r:.3f} mm")
    print()
    print(f"  {'Bond':22s}  {'end':>3s}  {'sph_r':>7s}"
          f"  {'overlap':>8s}  {'angle':>7s}  status")
    print(f"  {'----':22s}  {'---':>3s}  {'-----':>7s}"
          f"  {'-------':>8s}  {'-----':>7s}  ------")

    flags = []

    for bond in mol.bonds:
        a1    = mol.atoms[bond.atom1_idx]
        a2    = mol.atoms[bond.atom2_idx]
        r1, r2 = atom_r(a1), atom_r(a2)
        label  = f"{a1.element}{bond.atom1_idx}-{a2.element}{bond.atom2_idx}"

        for atom, r, end_lbl in [(a1, r1, "a1"), (a2, r2, "a2")]:
            if t_r >= r:
                print(f"  {label:22s}  {end_lbl:>3s}  DEGENERATE: tube_r >= sphere_r")
                flags.append((label, end_lbl, 0.0, 0.0, "GAP"))
                continue

            ov  = r - t_r
            z   = math.sqrt(r * r - t_r * t_r)
            ang = math.degrees(math.asin(min(1.0, z / r)))

            if ov < 0.3 or ang < 10.0:
                status = "GAP"
            elif ov < 1.0 or ang < 20.0:
                status = "MARGINAL"
            else:
                status = "ok"

            mark = "  <--" if status != "ok" else ""
            print(f"  {label:22s}  {end_lbl:>3s}  {r:7.3f}"
                  f"  {ov:8.3f}  {ang:7.1f}  {status}{mark}")

            if status != "ok":
                flags.append((label, end_lbl, ov, ang, status))

    print()
    if flags:
        print(f"  {len(flags)} junction(s) flagged:")
        for lbl, end, ov, ang, st in flags:
            print(f"    {lbl} ({end}):  overlap={ov:.3f} mm"
                  f"  angle={ang:.1f} deg  [{st}]")
    else:
        print("  All junctions ok.")
    print("=" * 70)


def export_model(shape, filepath, fmt="step"):
    """Export a CadQuery Shape (solid or compound) to STEP or STL."""
    import cadquery as cq
    if fmt in ("step", "stp"):
        cq.exporters.export(shape, filepath, exportType="STEP")
    elif fmt == "stl":
        cq.exporters.export(shape, filepath, exportType="STL",
                           tolerance=0.01, angularTolerance=0.1)
    else:
        raise ValueError(f"Unsupported format: {fmt}")


