#!/usr/bin/env python3
"""
mol2step.py — Generate solid STEP/BREP/STL CAD files of ball-and-stick
molecular models from molecular geometry files (MOL/SDF, XYZ, PDB, CJSON).

Atom spheres are sized by van der Waals radius. Bond tubes are sized by
the van der Waals radius of hydrogen times --bond-scale.

Output formats:
  STEP (default): each atom written as a true SPHERICAL_SURFACE with a
      VERTEX_LOOP boundary; each bond as an OCCT-walked cylinder. Produces
      N_atoms + N_bond_strands separate MANIFOLD_SOLID_BREP bodies in one
      file — no boolean fuse required, no seam-edge topology complexity.
  BREP: single fused solid via BRepAlgoAPI_Fuse (OCCT native format).
  STL:  triangulated mesh of the fused solid for direct slicing.

Requirements:
    conda/mamba install -c conda-forge cadquery numpy

Usage:
    python mol2step.py molecule.cjson -f step -o molecule.step
    python mol2step.py molecule.cjson -f brep -o molecule.brep
    python mol2step.py molecule.mol --vdw-scale 0.5 --bond-scale 0.3
    python mol2step.py molecule.mol --debug --info  # verbose validation

Scale convention (default --scale 10):
    1 Å VdW radius  →  1 cm sphere diameter
    Bond tubes sized to H VdW × bond-scale

Author: Generated by Claude for Ben King's molecular printing workflow
License: AGPL-3.0-or-later
"""

