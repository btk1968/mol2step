def parse_cjson_file(filepath, tol=0.4, min_bond_dist=MIN_BOND_DIST):
    """
    Parse an Avogadro2 Chemical JSON (CJSON) file.

    CJSON format (https://github.com/OpenChemistry/chemicaljson):
      {
        "chemicalJson": 1,        // or "chemical json": 0 for v0
        "name": "benzene",        // optional
        "atoms": {
          "elements": {
            "number": [6, 6, ...],     // atomic numbers
            "symbols": ["C", "C", ...] // optional, v1 only
          },
          "coords": {
            "3d": [x0, y0, z0, x1, y1, z1, ...]  // flat array, 3N
          }
        },
        "bonds": {                // optional
          "connections": {
            "index": [0, 1, 1, 2, ...]  // flat pairs: [a1,b1, a2,b2, ...]
          },
          "order": [2, 1, ...]    // bond orders
        }
      }

    If bonds are absent, they are inferred from covalent radii.
    Handles both CJSON v0 (spaces in keys) and v1 (camelCase).
    """
    mol = Molecule()
    with open(filepath) as f:
        data = json.load(f)

    # Validate it's CJSON
    if "chemicalJson" not in data and "chemical json" not in data:
        # Could be a plain JSON file — check for atoms key
        if "atoms" not in data:
            raise ValueError(
                f"{filepath}: not a recognized CJSON file "
                f"(missing 'chemicalJson' key and 'atoms' object)")

    mol.name = data.get("name", Path(filepath).stem)

    # --- Parse atoms ---
    atoms_obj = data.get("atoms", {})
    elements_obj = atoms_obj.get("elements", {})

    # Atomic numbers (required)
    atomic_numbers = elements_obj.get("number", [])

    # Element symbols (optional, v1 only) — prefer these if available
    symbols = elements_obj.get("symbols", [])

    # Coordinates: flat array [x0,y0,z0, x1,y1,z1, ...]
    coords_obj = atoms_obj.get("coords", {})
    coords_3d = coords_obj.get("3d", [])

    if not coords_3d:
        raise ValueError(f"{filepath}: no 3D coordinates found in "
                         f"atoms.coords.3d")

    num_atoms = len(coords_3d) // 3
    if len(coords_3d) != num_atoms * 3:
        raise ValueError(f"{filepath}: coords.3d length {len(coords_3d)} "
                         f"is not divisible by 3")

    if atomic_numbers and len(atomic_numbers) != num_atoms:
        raise ValueError(f"{filepath}: {len(atomic_numbers)} atomic numbers "
                         f"but {num_atoms} coordinate triples")

    for i in range(num_atoms):
        x = float(coords_3d[i * 3])
        y = float(coords_3d[i * 3 + 1])
        z = float(coords_3d[i * 3 + 2])

        # Determine element symbol
        if symbols and i < len(symbols):
            elem = symbols[i]
        elif atomic_numbers and i < len(atomic_numbers):
            z_num = int(atomic_numbers[i])
            elem = _Z_TO_SYMBOL.get(z_num, f"X{z_num}")
        else:
            elem = "X"

        mol.atoms.append(Atom(i, elem, x, y, z))

    # --- Parse bonds ---
    bonds_obj = data.get("bonds", {})
    connections = bonds_obj.get("connections", {})
    bond_indices = connections.get("index", [])
    bond_orders = bonds_obj.get("order", [])

    if bond_indices:
        num_bonds = len(bond_indices) // 2
        if len(bond_indices) != num_bonds * 2:
            print(f"  Warning: bonds.connections.index length "
                  f"{len(bond_indices)} not even, truncating")

        seen = set()
        for i in range(num_bonds):
            a1 = int(bond_indices[i * 2])
            a2 = int(bond_indices[i * 2 + 1])
            order = int(bond_orders[i]) if i < len(bond_orders) else 1
            if 0 <= a1 < num_atoms and 0 <= a2 < num_atoms:
                k = (min(a1, a2), max(a1, a2))
                if k in seen:
                    at1 = mol.atoms[a1]
                    at2 = mol.atoms[a2]
                    oname = {1: "single", 2: "double", 3: "triple"}.get(order, f"order-{order}")
                    print(f"  WARNING: duplicate {oname} bond in CJSON — "
                          f"keeping first, skipping this entry")
                    print(f"    {at1.element}[{a1}] @ "
                          f"({at1.x:.4f}, {at1.y:.4f}, {at1.z:.4f}) Å")
                    print(f"    {at2.element}[{a2}] @ "
                          f"({at2.x:.4f}, {at2.y:.4f}, {at2.z:.4f}) Å")
                    continue
                seen.add(k)
                mol.bonds.append(Bond(a1, a2, order))
    else:
        # No bond info — infer from covalent radii
        for i in range(num_atoms):
            for j in range(i + 1, num_atoms):
                ai, aj = mol.atoms[i], mol.atoms[j]
                d = np.linalg.norm(ai.pos - aj.pos)
                if min_bond_dist < d < ai.covalent_radius + aj.covalent_radius + tol:
                    mol.bonds.append(Bond(i, j))

    return mol


