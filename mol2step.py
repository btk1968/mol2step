@dataclass
class Atom:
    index: int
    element: str
    x: float
    y: float
    z: float

    @property
    def pos(self):
        return np.array([self.x, self.y, self.z])

    @property
    def vdw_radius(self):
        return VDW_RADII.get(self.element, DEFAULT_VDW_RADIUS)

    @property
    def covalent_radius(self):
        return COVALENT_RADII.get(self.element, DEFAULT_COVALENT_RADIUS)


@dataclass
class Bond:
    atom1_idx: int
    atom2_idx: int
    order: int = 1


@dataclass
class Molecule:
    name: str = "molecule"
    atoms: list = field(default_factory=list)
    bonds: list = field(default_factory=list)

    def center_on_origin(self):
        coords = np.array([[a.x, a.y, a.z] for a in self.atoms])
        com = coords.mean(axis=0)
        for a in self.atoms:
            a.x -= com[0]; a.y -= com[1]; a.z -= com[2]

    def bounding_box(self):
        coords = np.array([[a.x, a.y, a.z] for a in self.atoms])
        return coords.min(axis=0), coords.max(axis=0)


