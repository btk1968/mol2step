def parse_mol_file(filepath):
    filepath = Path(filepath)
    mol = Molecule()
    with open(filepath) as f:
        lines = f.readlines()
    if len(lines) < 4:
        raise ValueError(f"{filepath}: too short to be a valid V2000 MOL file")
    mol.name = lines[0].strip() or filepath.stem
    # V2000 counts line uses fixed-width fields: cols 0-2 = atom count, 3-5 = bond count
    counts_line = lines[3]
    try:
        na, nb = int(counts_line[0:3]), int(counts_line[3:6])
    except ValueError:
        raise ValueError(f"{filepath}: malformed counts line: {counts_line!r}")
    if len(lines) < 4 + na + nb:
        raise ValueError(
            f"{filepath}: file truncated (expected {4 + na + nb} lines, got {len(lines)})")
    # V2000 atom block: cols 0-9 = x, 10-19 = y, 20-29 = z, 31-33 = element symbol
    for i in range(na):
        ln = lines[4 + i]
        try:
            x, y, z = float(ln[0:10]), float(ln[10:20]), float(ln[20:30])
            elem = ln[31:34].strip()
        except (ValueError, IndexError):
            raise ValueError(f"{filepath}: malformed atom line {4 + i + 1}: {ln!r}")
        if not elem:
            raise ValueError(f"{filepath}: empty element symbol on atom line {4 + i + 1}")
        mol.atoms.append(Atom(i, elem, x, y, z))
    # V2000 bond block: cols 0-2 = atom1, 3-5 = atom2, 6-8 = bond order
    for i in range(nb):
        ln = lines[4 + na + i]
        try:
            a1, a2, order = int(ln[0:3]), int(ln[3:6]), int(ln[6:9])
        except (ValueError, IndexError):
            raise ValueError(f"{filepath}: malformed bond line {4 + na + i + 1}: {ln!r}")
        mol.bonds.append(Bond(a1 - 1, a2 - 1, order))
    return mol


def parse_xyz_file(filepath, tol=0.4, min_bond_dist=MIN_BOND_DIST):
    mol = Molecule()
    with open(filepath) as f:
        lines = f.readlines()
    na = int(lines[0].strip())
    mol.name = lines[1].strip() or Path(filepath).stem
    for i in range(na):
        p = lines[2 + i].split()
        elem = p[0][0].upper() + p[0][1:].lower() if len(p[0]) > 1 else p[0].upper()
        mol.atoms.append(Atom(i, elem, float(p[1]), float(p[2]), float(p[3])))
    for i in range(na):
        for j in range(i + 1, na):
            ai, aj = mol.atoms[i], mol.atoms[j]
            d = np.linalg.norm(ai.pos - aj.pos)
            if min_bond_dist < d < ai.covalent_radius + aj.covalent_radius + tol:
                mol.bonds.append(Bond(i, j))
    return mol


def _pdb_element_from_name(name_field):
    """Derive element symbol from PDB atom-name field (cols 12-16) as a fallback."""
    nm = name_field.strip()
    # Strip leading digits: "1HB", "2HD" etc. are hydrogen atoms
    nm = nm.lstrip("0123456789")
    alpha = "".join(c for c in nm if c.isalpha())[:2]
    if not alpha:
        return "X"
    if len(alpha) == 1:
        return alpha.upper()
    candidate = alpha[0].upper() + alpha[1].lower()
    # Accept two-letter symbol only if it's a known element; else fall back to one letter
    return candidate if candidate in VDW_RADII else alpha[0].upper()


def parse_pdb_file(filepath, tol=0.4, min_bond_dist=MIN_BOND_DIST):
    mol = Molecule()
    mol.name = Path(filepath).stem
    serial_map = {}
    with open(filepath) as f:
        lines = f.readlines()
    idx = 0
    for line in lines:
        if line[:6].strip() in ("ATOM", "HETATM"):
            elem = line[76:78].strip()
            if not elem:
                elem = _pdb_element_from_name(line[12:16])
            mol.atoms.append(Atom(idx, elem, float(line[30:38]),
                                  float(line[38:46]), float(line[46:54])))
            serial_map[int(line[6:11])] = idx
            idx += 1
    seen = set()
    conect = False
    for line in lines:
        if line.startswith("CONECT"):
            conect = True
            parts = line[6:].split()
            if not parts:
                continue
            i1 = serial_map.get(int(parts[0]))
            if i1 is None:
                continue
            for s in parts[1:]:
                i2 = serial_map.get(int(s))
                if i2 is None:
                    continue
                k = (min(i1, i2), max(i1, i2))
                if k not in seen:
                    seen.add(k)
                    mol.bonds.append(Bond(i1, i2))
    if not conect:
        n = len(mol.atoms)
        for i in range(n):
            for j in range(i + 1, n):
                ai, aj = mol.atoms[i], mol.atoms[j]
                d = np.linalg.norm(ai.pos - aj.pos)
                if min_bond_dist < d < ai.covalent_radius + aj.covalent_radius + tol:
                    mol.bonds.append(Bond(i, j))
    return mol


def load_molecule(filepath, tol=0.4, min_bond_dist=MIN_BOND_DIST):
    ext = Path(filepath).suffix.lower()
    if ext in (".mol", ".sdf"):
        return parse_mol_file(filepath)
    elif ext == ".xyz":
        return parse_xyz_file(filepath, tol, min_bond_dist)
    elif ext == ".pdb":
        return parse_pdb_file(filepath, tol, min_bond_dist)
    elif ext in (".cjson", ".json"):
        return parse_cjson_file(filepath, tol, min_bond_dist)
    else:
        raise ValueError(f"Unsupported: {ext}. Use .mol .sdf .xyz .pdb .cjson .json")


def validate_molecule(mol):
    """
    Check for duplicate atom positions and duplicate bonds.
    Prints warnings; returns the number of problems found.
    """
    problems = 0

    # Duplicate atom positions (within 1e-4 Å)
    pos_seen = {}
    for a in mol.atoms:
        key = tuple(np.round(a.pos, 4))
        if key in pos_seen:
            print(f"  WARNING: atom {a.element}{a.index} shares position "
                  f"{key} with atom {pos_seen[key]} — coincident spheres")
            problems += 1
        else:
            pos_seen[key] = f"{a.element}{a.index}"

    # Duplicate bonds
    bond_seen = set()
    order_names = {1: "single", 2: "double", 3: "triple"}
    for b in mol.bonds:
        k = (min(b.atom1_idx, b.atom2_idx), max(b.atom1_idx, b.atom2_idx))
        if k in bond_seen:
            a1 = mol.atoms[b.atom1_idx]
            a2 = mol.atoms[b.atom2_idx]
            oname = order_names.get(b.order, f"order-{b.order}")
            print(f"  WARNING: duplicate {oname} bond "
                  f"{a1.element}[{b.atom1_idx}]-{a2.element}[{b.atom2_idx}]"
                  f" — coincident cylinders will corrupt boolean fuse")
            print(f"    {a1.element}[{b.atom1_idx}] @ "
                  f"({a1.x:.4f}, {a1.y:.4f}, {a1.z:.4f}) Å")
            print(f"    {a2.element}[{b.atom2_idx}] @ "
                  f"({a2.x:.4f}, {a2.y:.4f}, {a2.z:.4f}) Å")
            problems += 1
        else:
            bond_seen.add(k)

    return problems


def _check_geometry_singularities(mol):
    """
    Check for geometric configurations that may cause numerical issues.

    Checks performed:
    1. Planarity — via PCA eigenvalue ratio on atom coordinates.
       A planar molecule has one near-zero eigenvalue.  OCCT BRepAlgoAPI_Fuse
       is known to produce inverted face normals for exactly-planar inputs.
    2. Near-threshold bond directions — bonds where |nz| ≈ 0.707, which is
       the switching point between the two reference vectors used in
       _make_cylinder and _bond_offsets.  Not a true singularity (cross
       product is non-zero at that angle), but useful for diagnostics.

    Prints notes; does not abort.  Returns a dict of detected conditions.
    """
    coords = np.array([a.pos for a in mol.atoms], dtype=float)
    n = len(coords)
    conditions = {}

    if n < 2:
        return conditions

    # ── 1. Planarity via PCA ───────────────────────────────────────────────
    centred = coords - coords.mean(axis=0)
    cov = (centred.T @ centred) / n
    # eigvalsh returns eigenvalues in ascending order
    eigvals = np.linalg.eigvalsh(cov)
    lam_max = eigvals[2] if eigvals[2] > 0 else 1.0
    ratio = eigvals[0] / lam_max   # out-of-plane variance / in-plane variance

    if ratio < 1e-8:
        conditions['planar'] = True
        print(f"  NOTE geometry: molecule is planar "
              f"(out-of-plane PCA variance ratio {ratio:.1e}); "
              f"OCCT boolean fuse may produce inverted face normals")
    elif ratio < 1e-3:
        conditions['near_planar'] = True
        print(f"  NOTE geometry: molecule is near-planar "
              f"(out-of-plane PCA variance ratio {ratio:.1e})")

    # ── 2. Bond directions near the reference-switching threshold ──────────
    # _make_cylinder / _bond_offsets switch from Z-ref to X-ref at |nz|=0.707.
    # At that exact angle the cross product magnitude is 0.707 — not singular —
    # but bonds close to ±Z (|nz|→1) or ±XY (|nz|→0) with the wrong ref
    # chosen would give a small cross product.  Our guard below catches that;
    # we flag here for visibility.
    SWITCH = 0.707
    MARGIN = 0.02
    near_thresh = []
    for bond in mol.bonds:
        a1, a2 = mol.atoms[bond.atom1_idx], mol.atoms[bond.atom2_idx]
        d = a2.pos - a1.pos
        length = np.linalg.norm(d)
        if length < 1e-8:
            continue
        nz = abs(d[2] / length)
        if abs(nz - SWITCH) < MARGIN:
            near_thresh.append(
                f"{a1.element}[{bond.atom1_idx}]-"
                f"{a2.element}[{bond.atom2_idx}] (|nz|={nz:.3f})"
            )
    if near_thresh:
        conditions['near_threshold_bonds'] = near_thresh
        print(f"  NOTE geometry: {len(near_thresh)} bond(s) near reference-"
              f"switching threshold (|nz|≈0.707): {', '.join(near_thresh)}")

    return conditions


