def sphere_radius_mm(vdw_angstroms, scale, vdw_scale):
    """VdW radius → model sphere radius in mm."""
    return vdw_angstroms * vdw_scale * scale / 2.0


def tube_radius_mm(scale, bond_scale, override=None):
    """Compute bond tube radius from H VdW and scale factors."""
    if override is not None:
        return override
    return VDW_RADII["H"] * bond_scale * scale / 2.0


def _atom_r(vdw_angstroms, scale, vdw_scale, t_r):
    """Effective atom sphere radius, clamped so the sphere always protrudes past the tube."""
    return max(sphere_radius_mm(vdw_angstroms, scale, vdw_scale),
               t_r + max(0.05, t_r * 0.01))


def validate_geometry(mol, scale, vdw_scale, bond_scale,
                      tube_radius_override=None):
    """
    Validate spatial contact between all spheres and tubes.
    Pure numpy — does NOT require CadQuery.
    """
    t_r = tube_radius_mm(scale, bond_scale, tube_radius_override)

    print("\n  ── Spatial contact validation ──")
    issues = 0

    for bond in mol.bonds:
        a1, a2 = mol.atoms[bond.atom1_idx], mol.atoms[bond.atom2_idx]
        p1, p2 = a1.pos * scale, a2.pos * scale
        d = p2 - p1
        length = np.linalg.norm(d)
        if length < 0.01:
            print(f"  !! Zero-length bond {a1.element}{bond.atom1_idx}-"
                  f"{a2.element}{bond.atom2_idx}")
            issues += 1
            continue
        d_hat = d / length

        r1 = _atom_r(a1.vdw_radius, scale, vdw_scale, t_r)
        r2 = _atom_r(a2.vdw_radius, scale, vdw_scale, t_r)

        # Cylinder goes center-to-center (no extension)
        cyl_start = p1
        cyl_end = p2
        cyl_length = length

        raw = _bond_offsets(d_hat, bond.order, t_r)
        kind_label = "single" if bond.order == 1 else None
        offsets = [(off, cr, kind_label or f"multi-k{k}")
                   for k, (off, cr) in enumerate(raw)]

        for off, cr, kind in offsets:
            for label, center, sph_r in [
                (f"{a1.element}{bond.atom1_idx}", p1, r1),
                (f"{a2.element}{bond.atom2_idx}", p2, r2),
            ]:
                axis_origin = cyl_start + off
                v = center - axis_origin
                proj = np.dot(v, d_hat)
                closest = axis_origin + proj * d_hat
                axis_dist = np.linalg.norm(center - closest)

                # For center-to-center: atom center is at proj=0 or proj=length
                # The cylinder endpoint coincides with atom center
                # Overlap = sphere extends past cylinder end along axis
                # Overlap depth along axis = sph_r (for centered bonds)
                #                          = sqrt(sph_r^2 - axis_dist^2) for offset
                if axis_dist < sph_r:
                    depth = math.sqrt(sph_r**2 - axis_dist**2)
                    in_range = (-0.01 <= proj <= cyl_length + 0.01)
                    # Also check sphere excess over tube
                    excess = sph_r - cr
                    status = "OK" if (in_range and excess > 0) else \
                             "TANGENT" if (in_range and excess <= 0) else \
                             "AXIS_SHORT"
                elif axis_dist < sph_r + cr:
                    depth = 0
                    in_range = (-0.01 <= proj <= cyl_length + 0.01)
                    status = "PARTIAL" if in_range else "MISS"
                else:
                    depth = 0
                    status = "NO_CONTACT"
                    in_range = False

                ok = status == "OK"
                if not ok:
                    issues += 1
                sym = "  " if ok else ">>"
                off_mag = np.linalg.norm(off)
                off_s = f"off={off_mag:.2f}" if off_mag > 0.01 else "ctr"
                print(f"  {sym} {a1.element}{bond.atom1_idx}-"
                      f"{a2.element}{bond.atom2_idx} -> {label}: "
                      f"ax_d={axis_dist:.3f} sph_r={sph_r:.2f} "
                      f"cyl_r={cr:.2f} proj={proj:.1f}/{cyl_length:.1f} "
                      f"depth={depth:.2f} excess={sph_r-cr:.2f} "
                      f"{off_s} {kind} [{status}]")

    if issues:
        print(f"\n  !! {issues} issues found !!")
    else:
        print(f"\n  All {len(mol.bonds)} bonds validated — "
              f"sphere_r > tube_r at every junction.")
    return issues


def build_model(mol, scale=10.0, vdw_scale=1.0, bond_scale=1.0,
                tube_radius_override=None,
                no_fillet=False, add_base=False, base_thickness=3.0,
                base_margin=5.0):
    """
    Build ball-and-stick molecular model as a single fused BREP solid.

    All sphere and cylinder primitives are collected into a flat list and
    fused in one BRepAlgoAPI_Fuse call (multi-tool mode).

    --no-fillet : outputs overlapping sphere+cylinder primitives as a
                  Compound (no boolean, always valid STEP).
    --union     : accepted for backward compatibility; the default path
                  always produces a single fused solid.
    """
    if not mol.atoms:
        raise ValueError("Molecule has no atoms — nothing to build.")

    import cadquery as cq
    from OCP.BRepAlgoAPI import BRepAlgoAPI_Fuse
    from OCP.TopTools import TopTools_ListOfShape

    t_r = tube_radius_mm(scale, bond_scale, tube_radius_override)

    # ── Sizing table ──────────────────────────────────────────────────────
    print(f"  Scale: {scale} mm/A  VdW: {vdw_scale}x  Bond: {bond_scale}x")
    print(f"  Tube radius: {t_r:.3f} mm")
    print()
    print(f"  {'Elem':4s}  {'sph_r':>7s}  {'overlap':>8s}  {'angle':>7s}  status")
    print(f"  {'----':4s}  {'-----':>7s}  {'-------':>8s}  {'-----':>7s}  ------")
    for elem in sorted(set(a.element for a in mol.atoms)):
        vdw = VDW_RADII.get(elem, DEFAULT_VDW_RADIUS)
        r   = _atom_r(vdw, scale, vdw_scale, t_r)
        ov  = r - t_r
        z   = math.sqrt(max(0.0, r*r - t_r*t_r))
        ang = math.degrees(math.asin(min(1.0, z / r)))
        st  = "ok" if ov >= 1.0 else ("marginal" if ov >= 0.3 else "GAP RISK")
        print(f"  {elem:4s}  {r:7.3f}  {ov:8.3f}  {ang:7.1f}  {st}")
    print()

    gap_count = 0
    for bond in mol.bonds:
        for atom in (mol.atoms[bond.atom1_idx], mol.atoms[bond.atom2_idx]):
            if (_atom_r(atom.vdw_radius, scale, vdw_scale, t_r) - t_r) < 0.3:
                gap_count += 1
    if gap_count:
        print(f"  WARNING: {gap_count} junctions have overlap < 0.3 mm"
              f" -- reduce --bond-scale or raise --vdw-scale")
    else:
        print("  All junction overlaps >= 0.3 mm  (ok)")
    print()

    _check_geometry_singularities(mol)

    # ── Path 1: --no-fillet compound (validated, no boolean) ─────────────
    if no_fillet:
        shapes = []
        for atom in mol.atoms:
            pos = np.asarray(atom.pos * scale, dtype=float)
            shapes.append(_make_sphere(pos, _atom_r(atom.vdw_radius, scale, vdw_scale, t_r)).val())
        n_cyl = 0
        for bond in mol.bonds:
            a1 = mol.atoms[bond.atom1_idx]
            a2 = mol.atoms[bond.atom2_idx]
            p1 = np.asarray(a1.pos * scale, dtype=float)
            p2 = np.asarray(a2.pos * scale, dtype=float)
            L  = float(np.linalg.norm(p2 - p1))
            if L < 0.01:
                continue
            d = (p2 - p1) / L
            for off, cyl_r in _bond_offsets(d, bond.order, t_r):
                cyl = _make_cylinder(p1 + off, p2 + off, cyl_r)
                if cyl is not None:
                    shapes.append(cyl.val())
                    n_cyl += 1
        print(f"  Bodies: {len(mol.atoms)} spheres + {n_cyl} cylinders "
              f"(no boolean — overlapping primitives)")
        return cq.Compound.makeCompound(shapes)

    # ── Path 2: multi-tool fuse ───────────────────────────────────────────

    # Build all sphere and cylinder primitives as a flat list
    all_shapes = []

    for atom in mol.atoms:
        pos = np.asarray(atom.pos * scale, dtype=float)
        all_shapes.append(_make_sphere(pos, _atom_r(atom.vdw_radius, scale, vdw_scale, t_r)).val())

    n_cyl = 0
    for bond in mol.bonds:
        a1 = mol.atoms[bond.atom1_idx]
        a2 = mol.atoms[bond.atom2_idx]
        p1 = np.asarray(a1.pos * scale, dtype=float)
        p2 = np.asarray(a2.pos * scale, dtype=float)
        L  = float(np.linalg.norm(p2 - p1))
        if L < 0.01:
            continue
        d = (p2 - p1) / L
        for off, cyl_r in _bond_offsets(d, bond.order, t_r):
            cyl = _make_cylinder(p1 + off, p2 + off, cyl_r)
            if cyl is not None:
                all_shapes.append(cyl.val())
                n_cyl += 1

    print(f"  Primitives: {len(mol.atoms)} spheres + {n_cyl} cylinders")

    # Single multi-tool fuse: first shape is the argument, rest are tools.
    # One kernel call avoids the incremental pairwise STEP-export orientation bug.
    if len(all_shapes) == 1:
        result = all_shapes[0]
    else:
        # Sequential pairwise fuse.
        # Multi-tool mode (SetArguments/SetTools with all shapes at once)
        # produces inverted face normals for planar molecules: at z=0
        # intersection edges the dihedral angle is exactly 0° or 180°,
        # making the ± face-classification sign ambiguous.  Pairwise fuse
        # resolves each pair in isolation and avoids the global sign flip.
        # Sequential pairwise fuse.
        # Multi-tool mode (SetArguments/SetTools with all shapes at once)
        # produces inverted face normals for planar molecules: at z=0
        # intersection edges the dihedral angle is exactly 0° or 180°,
        # making the ± face-classification sign ambiguous.  Pairwise fuse
        # resolves each pair in isolation and avoids the global sign flip.
        #
        # _as_solid is called once at the end, not inside the loop:
        # calling it on each intermediate result can corrupt later steps if
        # a non-overlapping pair produces a temporary compound.
        print(f"  Fusing {len(all_shapes)} primitives (sequential pairwise)...")
        result = all_shapes[0]
        failed = 0
        for shape in all_shapes[1:]:
            arg  = TopTools_ListOfShape(); arg.Append(result.wrapped)
            tool = TopTools_ListOfShape(); tool.Append(shape.wrapped)
            fuser = BRepAlgoAPI_Fuse()
            fuser.SetArguments(arg)
            fuser.SetTools(tool)
            fuser.SetFuzzyValue(1e-6)
            fuser.Build()
            if fuser.IsDone():
                stepped = cq.Shape.cast(fuser.Shape())
                # Unwrap compound→solid without orientation correction mid-loop
                solids = stepped.Solids()
                result = solids[0] if len(solids) == 1 else stepped
            else:
                failed += 1

        result = _as_solid(result)
        _diag_orientation(result, "after_fuse")
        if failed:
            print(f"  WARNING: {failed} pairwise fuse step(s) failed — "
                  f"result may be incomplete")
        print(f"  Fuse complete: {len(result.Faces())} faces, "
              f"{len(result.Edges())} edges")

    # ── Optional base plate ────────────────────────────────────────────────
    if add_base:
        max_r = max(_atom_r(a.vdw_radius, scale, vdw_scale, t_r) for a in mol.atoms)
        bb_min, bb_max = mol.bounding_box()
        bmin = np.asarray(bb_min * scale, dtype=float)
        bmax = np.asarray(bb_max * scale, dtype=float)
        z_bot = float(bmin[2]) - max_r - 0.5
        w  = float(bmax[0] - bmin[0]) + 2 * base_margin + 2 * max_r
        dd = float(bmax[1] - bmin[1]) + 2 * base_margin + 2 * max_r
        cx = float(bmin[0] + bmax[0]) / 2.0
        cy = float(bmin[1] + bmax[1]) / 2.0
        base_wp = (cq.Workplane("XY")
                   .box(w, dd, base_thickness)
                   .translate(cq.Vector(cx, cy, z_bot - base_thickness / 2.0)))
        try:
            base_wp = base_wp.edges("|Z").fillet(base_thickness * 0.4)
        except Exception:
            pass
        base_solid = base_wp.val()
        base_args  = TopTools_ListOfShape()
        base_args.Append(result.wrapped)
        base_tools = TopTools_ListOfShape()
        base_tools.Append(base_solid.wrapped)
        bf = BRepAlgoAPI_Fuse()
        bf.SetArguments(base_args)
        bf.SetTools(base_tools)
        bf.Build()
        if bf.IsDone():
            result = _as_solid(cq.Shape.cast(bf.Shape()))
        else:
            return cq.Compound.makeCompound([result, base_solid])

    return result


